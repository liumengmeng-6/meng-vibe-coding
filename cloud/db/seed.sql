-- ============================================================
-- seed.sql —— 种子脚本（Day 16 · 板块③）
-- 项目：meng-vibe-coding（出行规划小助手）｜ 后端区 cloud/
-- 数据库：PostgreSQL（CloudBase 控制台的「SQL 型数据库」）
-- ============================================================
--
-- 【这份文件是干什么的】
--   schema.sql 只搭了两张空表。这份文件负责「把数据灌进去」。
--   灌的量和出处：
--     cities  370 行  ←  app.js 的 CN_CITIES（城市白名单）
--     places   12 行  ←  app.js 的 CITY_HIGHLIGHTS（成都 6 条 + 重庆 6 条）
--
-- ⚠️ 本文件里的数据不是我编的，是用 .git/_test-day16/gen-seed.js
--    从 app.js 里原样抽出来的。改了 app.js 的数据，重跑一次那个脚本
--    就能重新生成这份文件，两边不会对不上。（项目规矩 8.7：数据必须有出处）
--
-- 【怎么用】
--   1. 先确认 schema.sql 已经跑过了（表得先在）
--   2. 打开 CloudBase 控制台 → 左侧「SQL 型数据库」→ PostgreSQL 管理
--      → 点左侧「SQL 编辑器」
--   3. 把本文件全文粘进去，执行
--   4. 成功的样子：9 条 INSERT 全部执行成功
--      （cities 8 条 + places 1 条），每条后面会显示插入了多少行
--
-- 【执行顺序：必须 cities 在前】
--   places 的每一行都要去 cities 里查「成都的 id 是几」。
--   城市还没灌进去，子查询会查到空值，那一行就插不进去。
--   所以本文件从上往下整段执行，不要跳着只跑 places 那一段。
--
-- 【这份文件可以重复执行，而且第二遍不会报错】
--   靠的不是运气，是 schema.sql 里那两个唯一约束：
--     cities 的 CONSTRAINT uk_cities_name      UNIQUE (name)
--     places 的 CONSTRAINT uk_places_city_name UNIQUE (city_id, name)
--   没有它们，数据库认不出「这行已经有了」，第二遍就会报唯一冲突。
--
--   两张表的重复行为故意不一样，这里说清楚：
--     ｜ cities ｜ 已存在就【跳过】（ON CONFLICT ... DO NOTHING）。
--     ｜        ｜ 这张表除了 name 没有别的可更新字段（name 本身就是唯一键，
--     ｜        ｜ 改它等于插新行），所以跳过就是全部。
--     ｜ places ｜ 已存在就【更新】type / price / note
--     ｜        ｜ （ON CONFLICT ... DO UPDATE SET x = EXCLUDED.x）。
--     ｜        ｜ 所以你改了 app.js 里的价格，重跑一遍，库里就同步了 ——
--     ｜        ｜ 这正是当初选它、而没选「一律跳过」的原因。
--
--   ⚠️ 但要如实说明一个局限：重复执行管的是「改」和「加」，
--      不管「删」。你在 app.js 里删掉一条地点，库里那行不会自己消失，
--      得手动 DELETE。这个以后真需要了再说，今天不处理。
--
--   ⚠️ 另一个小提醒（不是错）：即使这行最后没插进去（冲突被跳过），
--      自增序列也已经往前走了一格。所以重复跑几遍，之后新插行的 id
--      会往上跳号 —— 不影响任何功能，只是号码不连号。
--
-- ============================================================


